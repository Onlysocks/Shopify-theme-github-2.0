const assert = require('node:assert/strict');
const { calculate } = require('./onlysocks-bundle-pricing.js');
const prices = amounts => amounts.map(price => ({ price }));
let result = calculate(prices([2000, 2000, 2000, 2000, 2000, 2000]), 1, 10, true);
assert.deepEqual(result, { original:12000, total:9000, free:[0], each:1500 });
result = calculate(prices([3000, 1000, 2500, 2000, 1800, 2200]), 1, 20, true);
assert.deepEqual(result.free, [1]); assert.equal(result.total, 9200); assert.equal(result.original,12500);
result = calculate(prices([3000, 2800, 2700, 2600, 2500, 2400, 2300, 1100, 900]), 2, 10, true);
assert.deepEqual(result.free, [8,7]); assert.equal(result.total,16470); assert.equal(result.each,1830);
assert.deepEqual(calculate(prices([1000,1000,1000]),2,0,true).free,[0,1]);
assert.deepEqual(calculate(prices([3000,4000,500]),1,0,true).free,[2]);
result = calculate(prices([2000,null,1000]),1,20,false);
assert.deepEqual(result.free,[]); assert.equal(result.total,3000);
assert.equal(calculate(prices([2999,1999]),0,15,true).total,4248);
assert.equal(calculate(prices([2000]),0,0,true).each,2000);
assert.equal(calculate([],0,0,false).total,0);
const fs = require('node:fs');
const source = fs.readFileSync(require('node:path').join(__dirname,'../sections/main-product.liquid'),'utf8');
const schema = JSON.parse(source.split('{% schema %}')[1].split('{% endschema %}')[0]);
const block = schema.blocks.find(b => b.type === 'onlysocks_bundle');
assert.ok(block); assert.equal(block.limit,1);
const ids = block.settings.filter(s=>s.id).map(s=>s.id);
assert.equal(new Set(ids).size,ids.length);
for (const setting of block.settings.filter(s=>s.type==='range')) assert.ok(setting.default >= setting.min && setting.default <= setting.max);
assert.equal(block.settings.find(s=>s.id==='checkout_ready').default,false);
console.log('Passed: cheapest pairs, ties, changed selections, incomplete bundles, discounts, rounding and block schema.');
